import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const extension = path.join(root, 'extension');

// MV3 content scripts are classic scripts, so the ESM package is bundled into one IIFE.
// `sahajlipi/dom` resolves through this package's own exports map, as a consumer's would.
const result = await build({
  absWorkingDir: root,
  entryPoints: [path.join(extension, 'src/content.js')],
  outfile: path.join(extension, 'dist/content.js'),
  bundle: true, format: 'iife', platform: 'browser', target: 'chrome111',
  legalComments: 'inline',
  banner: { js: '// SahajLipi browser extension content script. Generated by tools/build-extension.js; do not edit.' },
  metafile: true,
});
const inputs = Object.keys(result.metafile.inputs);
if (!inputs.includes('src/dom.js')) throw new Error('content script did not bundle sahajlipi/dom');
console.log(`Extension content script: ${inputs.length} modules -> extension/dist/content.js`);
